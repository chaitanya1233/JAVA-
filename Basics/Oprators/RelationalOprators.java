package Oprators;

public class RelationalOprators {
    public static void main(String[] args) {
        int a = 2;
        int b = 4;
        System.out.println(a < b); // True
        System.out.println(a > b); // False
        System.out.println(a <= b); // True
        System.out.println(a >= b); // False
        System.out.println(a == b); // False
        System.out.println("------------------");
    }
}
