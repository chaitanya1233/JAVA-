public class Comparison {
    public static void main(String[] args) {
        System.out.println("Comparision oprators in java");
        int age = 18;
        int age2 = 43;
        System.out.println(age > age2);
        System.out.println(age < age2);
        System.out.println(age >= age2);
        System.out.println(age <= age2);
        System.out.println(age == age2);

    }
}
